"""Canonical Khaya schema: one dialect per supported backend."""

# Monitoring settings seeded by `python -m db init` and merged as in-memory
# defaults by the application whenever a row is absent.
SETTINGS_DEFAULTS = {'interval': 30, 'failure_threshold': 3, 'heartbeat_timeout': 180, 'subnet': '192.168.1.0/24'}

# Tables holding dashboard data; excluded from dumps only when noted.
DATA_TABLES = ('devices', 'observations', 'events', 'settings')
# Everything the application requires before it will start.
REQUIRED_TABLES = DATA_TABLES + ('schema_migrations',)

SCHEMAS = {
    'sqlite': '''
        CREATE TABLE IF NOT EXISTS devices (
            id TEXT PRIMARY KEY, name TEXT NOT NULL, target TEXT NOT NULL,
            type TEXT NOT NULL, location TEXT NOT NULL DEFAULT '',
            manufacturer TEXT NOT NULL DEFAULT '', mac TEXT NOT NULL DEFAULT '',
            notes TEXT NOT NULL DEFAULT '', connection TEXT NOT NULL DEFAULT 'wired',
            parent_id TEXT REFERENCES devices(id) ON DELETE SET NULL,
            method TEXT NOT NULL DEFAULT 'icmp', status TEXT NOT NULL DEFAULT 'unknown',
            last_check REAL, last_seen REAL, latency REAL, failures INTEGER NOT NULL DEFAULT 0,
            last_error TEXT NOT NULL DEFAULT '', heartbeat_hash TEXT,
            created_at REAL NOT NULL
        );
        CREATE TABLE IF NOT EXISTS observations (
            id INTEGER PRIMARY KEY, device_id TEXT REFERENCES devices(id) ON DELETE CASCADE,
            at REAL NOT NULL, reachable INTEGER, latency REAL, error TEXT NOT NULL DEFAULT ''
        );
        CREATE INDEX IF NOT EXISTS observation_device ON observations(device_id, at);
        CREATE TABLE IF NOT EXISTS events (
            id INTEGER PRIMARY KEY, at REAL NOT NULL, device_id TEXT, name TEXT NOT NULL,
            status TEXT NOT NULL, message TEXT NOT NULL
        );
        CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
        CREATE TABLE IF NOT EXISTS schema_migrations (name TEXT PRIMARY KEY, applied_at REAL NOT NULL);
    ''',
    'postgres': '''
        CREATE TABLE IF NOT EXISTS devices (
            id TEXT PRIMARY KEY, name TEXT NOT NULL, target TEXT NOT NULL,
            type TEXT NOT NULL, location TEXT NOT NULL DEFAULT '',
            manufacturer TEXT NOT NULL DEFAULT '', mac TEXT NOT NULL DEFAULT '',
            notes TEXT NOT NULL DEFAULT '', connection TEXT NOT NULL DEFAULT 'wired',
            parent_id TEXT REFERENCES devices(id) ON DELETE SET NULL,
            method TEXT NOT NULL DEFAULT 'icmp', status TEXT NOT NULL DEFAULT 'unknown',
            last_check DOUBLE PRECISION, last_seen DOUBLE PRECISION, latency DOUBLE PRECISION,
            failures INTEGER NOT NULL DEFAULT 0, last_error TEXT NOT NULL DEFAULT '',
            heartbeat_hash TEXT, created_at DOUBLE PRECISION NOT NULL
        );
        CREATE TABLE IF NOT EXISTS observations (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            device_id TEXT REFERENCES devices(id) ON DELETE CASCADE,
            at DOUBLE PRECISION NOT NULL, reachable INTEGER, latency DOUBLE PRECISION,
            error TEXT NOT NULL DEFAULT ''
        );
        CREATE INDEX IF NOT EXISTS observation_device ON observations(device_id, at);
        CREATE TABLE IF NOT EXISTS events (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            at DOUBLE PRECISION NOT NULL, device_id TEXT, name TEXT NOT NULL,
            status TEXT NOT NULL, message TEXT NOT NULL
        );
        CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
        CREATE TABLE IF NOT EXISTS schema_migrations (name TEXT PRIMARY KEY, applied_at DOUBLE PRECISION NOT NULL);
    ''',
}

# Migration bookkeeping exists before any migration is recorded, so legacy
# databases created by the application itself can be adopted.
MIGRATIONS_TABLE = {
    'sqlite': 'CREATE TABLE IF NOT EXISTS schema_migrations (name TEXT PRIMARY KEY, applied_at REAL NOT NULL)',
    'postgres': 'CREATE TABLE IF NOT EXISTS schema_migrations (name TEXT PRIMARY KEY, applied_at DOUBLE PRECISION NOT NULL)',
}

# Rebuilds a legacy devices table that still enforces unique addresses.
# Foreign keys must be off for the swap (children would cascade otherwise),
# so this runs through SqliteBackend.run_script_unchecked.
LEGACY_SQLITE_REBUILD = '''
    CREATE TABLE devices_new (
        id TEXT PRIMARY KEY, name TEXT NOT NULL, target TEXT NOT NULL,
        type TEXT NOT NULL, location TEXT NOT NULL DEFAULT '',
        manufacturer TEXT NOT NULL DEFAULT '', mac TEXT NOT NULL DEFAULT '',
        notes TEXT NOT NULL DEFAULT '', connection TEXT NOT NULL DEFAULT 'wired',
        parent_id TEXT REFERENCES devices(id) ON DELETE SET NULL,
        method TEXT NOT NULL DEFAULT 'icmp', status TEXT NOT NULL DEFAULT 'unknown',
        last_check REAL, last_seen REAL, latency REAL, failures INTEGER NOT NULL DEFAULT 0,
        last_error TEXT NOT NULL DEFAULT '', heartbeat_hash TEXT,
        created_at REAL NOT NULL
    );
    INSERT INTO devices_new (id, name, target, type, location, manufacturer, mac, notes, connection,
        parent_id, method, status, last_check, last_seen, latency, failures, last_error,
        heartbeat_hash, created_at)
        SELECT id, name, target, type, location, manufacturer, mac, notes, connection,
        parent_id, method, status, last_check, last_seen, latency, failures, last_error,
        heartbeat_hash, created_at FROM devices;
    DROP TABLE devices;
    ALTER TABLE devices_new RENAME TO devices;
'''
